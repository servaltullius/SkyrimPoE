"""Generate the C++ gem form tables from the ledger, bundle and gen0 baseline."""

import argparse
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from formid_ledger import (DEFAULT_GEM_BUNDLE, DEFAULT_LEDGER, DEFAULT_PUBLISHED, GENERATION_EDITOR_ID, ROOT,
                           check_gem_content_ids, index_entries, read_gem_ids, read_json)

OUTPUT = ROOT / "plugin/src/runtime/GemFormTables.generated.h"


def render() -> bytes:
    ledger = read_json(DEFAULT_LEDGER)
    bundle = read_json(DEFAULT_GEM_BUNDLE)
    problems = []
    entries = index_entries(ledger, "ledger", problems)
    baseline = index_entries(read_json(DEFAULT_PUBLISHED / "gen0.json"), "gen0", problems)
    check_gem_content_ids(bundle, entries, baseline, problems)
    if problems:
        raise ValueError("\n".join(problems))

    legacy = read_gem_ids(baseline)
    by_form = {int(row["form"]["formId"], 16): row for row in bundle}
    forms = {form_id: entry for form_id, entry in entries.items() if entry["category"] == "gem"}
    if forms.keys() != legacy.keys() | by_form.keys():
        raise ValueError("젬 실물 표와 세대별 키 표의 FormID 합집합 불일치")

    physical_rows = []
    for form_id, entry in sorted(forms.items()):
        row = by_form.get(form_id)
        missing_legacy = form_id not in legacy
        expected_key = None if missing_legacy else f"gem:{legacy[form_id]}"
        if entry["type"] != "MISC" or entry["legacyKey"] != expected_key:
            raise ValueError(f"젬 타입 또는 구판 키 불일치: {entry['editorId']}")
        if missing_legacy:
            status = "Staged"
        else:
            status = "Generation0" if row else "RetiringInGeneration1"
        content_id = row["contentId"] if row else ""
        physical_rows.append(
            f'        {{ 0x{form_id:06X}, GemFormStatus::{status}, "{legacy.get(form_id, "")}", '
            f'"{content_id}" }},')

    legacy_rows = [f'        {{ "{key}", 0x{form_id:06X} }},' for form_id, key in sorted(legacy.items())]
    content_rows = []
    for form_id, row in sorted(by_form.items()):
        shape, ready = row["shape"], row["ready"]
        if shape not in {f"S{n}" for n in range(1, 13)} or type(ready) is not bool:
            raise ValueError(f"실행 방식 또는 ready 오류: {row['contentId']}")
        if (shape == "S11") != row["contentId"].startswith("sup."):
            raise ValueError(f"콘텐츠 ID 접두와 실행 방식 불일치: {row['contentId']}")
        content_rows.append(
            f'        {{ "{row["contentId"]}", 0x{form_id:06X}, {str(ready).lower()}, GemExecution::{shape} }},')

    markers = [form_id for form_id, entry in entries.items() if entry["editorId"] == GENERATION_EDITOR_ID]
    if len(markers) > 1 or any(entries[form_id]["type"] != "GLOB" for form_id in markers):
        raise ValueError("세대 표시 GLOB 장부 항목 오류")
    marker = f"0x{markers[0]:06X}" if markers else "std::nullopt"

    lines = [
        "// Generated by tools/esp/gen_gem_tables.py. Do not edit.",
        "#pragma once", "", "#include <array>", "#include <cstdint>",
        "#include <optional>", "#include <string_view>", "",
        "namespace SkyrimPoE::Core::GemForms", "{",
        "    enum class GemFormStatus { Generation0, Staged, RetiringInGeneration1 };",
        "    enum class GemExecution { S1, S2, S3, S4, S5, S6, S7, S8, S9, S10, S11, S12 };", "",
        "    struct GemForm", "    {", "        std::uint32_t localFormId;",
        "        GemFormStatus status;", "        std::string_view legacyId;",
        "        std::string_view contentId;", "    };", "",
        "    struct LegacyGemKey", "    {", "        std::string_view gemId;",
        "        std::uint32_t localFormId;", "    };", "",
        "    struct ContentGemKey", "    {", "        std::string_view contentId;",
        "        std::uint32_t localFormId;", "        bool ready;",
        "        GemExecution execution;", "    };", "",
    ]
    for name, type_name, rows in (("kPhysicalForms", "GemForm", physical_rows),
                                  ("kLegacyKeys", "LegacyGemKey", legacy_rows),
                                  ("kContentKeys", "ContentGemKey", content_rows)):
        lines.extend([f"    inline constexpr std::array<{type_name}, {len(rows)}> {name} = {{{{",
                      *rows, "    }};", ""])
    lines.extend([f"    inline constexpr std::optional<std::uint32_t> kGenerationGlobal = {marker};", "}", ""])
    return "\n".join(lines).encode("utf-8")


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    try:
        generated = render()
        if args.check:
            if not OUTPUT.is_file() or OUTPUT.read_bytes() != generated:
                raise ValueError("젬 헤더가 장부와 다릅니다. gen_gem_tables.py로 다시 생성하세요.")
        else:
            OUTPUT.write_bytes(generated)
    except (OSError, ValueError, KeyError, TypeError) as exc:
        print(exc, file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
